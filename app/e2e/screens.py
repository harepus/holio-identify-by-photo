"""Receiving v2 browser checks and screenshots. Photo answers use labeled mocks."""
import sys
from pathlib import Path
from playwright.sync_api import expect, sync_playwright
APP = Path(__file__).resolve().parent.parent
OUT = APP / '.e2e-shots'
BASE = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:8781'
FRONT = APP.parent / 'server/tests/fixtures/photos/h009/photo1.jpg'
BACK = APP.parent / 'server/tests/fixtures/photos/h009/photo2.jpg'


def shot(page, name):
    page.wait_for_timeout(300)
    page.screenshot(path=str(OUT / f'v2-{name}.png'))


def run(page):
    page.goto(BASE + '/?mock=match')
    page.evaluate('localStorage.clear(); sessionStorage.clear()')
    page.reload()
    expect(page.locator('.po-head .badge')).to_have_text('Pending')
    shot(page, '01-order')
    page.get_by_role('button', name='Open scanner').click()
    page.get_by_text('Demo tools', exact=True).click()
    page.get_by_role('button', name='Superchips Paprika 140 g 7050122114607').click()
    expect(page.locator('.scan-banner')).to_contain_text('1/24')
    page.get_by_role('button', name='Undo last receipt').click()
    expect(page.locator('.cam-received')).to_have_count(0)
    expect(page.get_by_role('button', name='Undo last receipt')).to_have_count(0)
    print('[ok] known scan and undo')
    page.get_by_role('button', name='No barcode?', exact=True).click()
    expect(page.get_by_role('button', name='Identify by photo', exact=True)).to_be_focused()
    page.keyboard.press('Shift+Tab')
    expect(page.get_by_role('button', name='Back to scanning', exact=True)).to_be_focused()
    page.keyboard.press('Tab')
    expect(page.get_by_role('button', name='Identify by photo', exact=True)).to_be_focused()
    page.keyboard.press('Escape')
    expect(page.get_by_role('button', name='No barcode?', exact=True)).to_be_focused()
    page.get_by_role('button', name='Search manually', exact=True).click()
    expect(page.get_by_label('Name, SKU or barcode')).to_be_focused()
    page.keyboard.press('Escape')
    expect(page.get_by_role('button', name='Search manually', exact=True)).to_be_focused()
    print('[ok] keyboard focus containment, Escape and return to scanner')
    page.get_by_role('button', name='Unknown code 7031234567890').click()
    shot(page, '02-unknown')
    page.get_by_role('dialog').get_by_role('button', name='Search manually').click()
    page.get_by_label('Name, SKU or barcode').fill('sour')
    expect(page.locator('.search-results .product-row')).to_have_count(1)
    shot(page, '03-search')
    page.locator('.search-results .product-row').click()
    page.get_by_role('spinbutton', name='Quantity', exact=True).fill('3')
    page.get_by_role('textbox', name='Location', exact=True).fill('B-02-01')
    shot(page, '04-review')
    page.get_by_role('button', name='Receive 3', exact=True).click()
    expect(page.locator('.scan-banner')).to_contain_text('3/24')
    page.get_by_role('button', name='Unknown code 7031234567890').click()
    expect(page.locator('.scan-banner')).to_contain_text('4/24')
    page.get_by_text('Demo tools', exact=True).click()
    page.locator('.page').evaluate('(el) => el.scrollTop = 0')
    shot(page, '05-linked-scan')
    print('[ok] manual search, quantity, location, extra barcode, next scan')
    page.get_by_role('button', name='Back', exact=True).click()
    page.locator('.line', has_text='Sour Cream').click()
    expect(page.get_by_role('textbox', name='Location', exact=True)).to_have_value('B-02-01')
    page.get_by_role('spinbutton', name='Quantity', exact=True).fill('21')
    page.get_by_role('button', name='Receive 21', exact=True).click()
    expect(page.get_by_role('button', name='Receive anyway')).to_be_visible()
    shot(page, '06-over-warning')
    page.get_by_role('button', name='Receive anyway').click()
    page.get_by_role('button', name='Back', exact=True).click()
    expect(page.locator('.line', has_text='Sour Cream')).to_contain_text('Over received')
    shot(page, '07-over-received')
    print('[ok] explicit over-receipt and status')
    page.get_by_role('button', name='Open scanner').click()
    page.get_by_role('button', name='Search manually', exact=True).click()
    page.get_by_role('button', name='Search all products', exact=True).click()
    page.get_by_label('Name, SKU or barcode').fill('SKU-1254')
    page.locator('.search-results .product-row').click()
    expect(page.get_by_role('dialog', name='Not on this order')).to_be_visible()
    expect(page.get_by_role('dialog').get_by_role('button', name='Receive', exact=False)).to_have_count(0)
    shot(page, '08-off-order')
    page.get_by_role('button', name='Back to scanning').click()
    print('[ok] register search and off-order refusal')
    page.get_by_role('button', name='No barcode?', exact=True).click()
    page.get_by_role('button', name='Identify by photo', exact=True).click()
    page.locator('.hid-file').set_input_files(str(FRONT))
    expect(page.locator('.hid-preview .hid-lab')).to_have_text('Front')
    expect(page.locator('.hid-btnrow').get_by_role('button', name='Back photo', exact=True)).to_be_visible()
    shot(page, '10-front-taken')
    page.locator('.hid-btnrow').get_by_role('button', name='Back photo', exact=True).click()
    page.locator('.hid-file').set_input_files(str(BACK))
    expect(page.locator('.hid-preview .hid-lab')).to_have_text('Back')
    shot(page, '11-front-and-back')
    page.get_by_role('button', name='Identify', exact=True).click()
    page.get_by_role('button', name='Review receipt', exact=True).click()
    expect(page.get_by_role('dialog', name='Review receipt')).to_be_visible()
    expect(page.get_by_role('checkbox')).to_have_count(0)
    page.get_by_role('button', name='Cancel', exact=True).click()
    print('[ok] mock photo result reviews without counting or invented barcode')
    page.goto(BASE + '/?mock=error')
    page.get_by_role('button', name='Open scanner').click()
    page.get_by_role('button', name='No barcode?', exact=True).click()
    page.get_by_role('button', name='Identify by photo', exact=True).click()
    page.locator('.hid-file').set_input_files(str(FRONT))
    page.get_by_role('button', name='Identify', exact=True).click()
    expect(page.get_by_text('Identification unavailable', exact=True)).to_be_visible()
    shot(page, '09-photo-error')
    page.get_by_role('button', name='Search manually', exact=True).click()
    expect(page.get_by_label('Name, SKU or barcode')).to_be_visible()
    print('[ok] photo error recovery')
    for width in [360, 430]:
        page.set_viewport_size({'width': width, 'height': 800})
        expect(page.get_by_role('button', name='Search all products', exact=True)).to_be_in_viewport()
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    print('[ok] 360 and 430 px layouts')

if __name__ == '__main__':
    OUT.mkdir(exist_ok=True)
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport={'width':390,'height':844}, device_scale_factor=2)
        errors=[]
        page.on('pageerror', lambda error: errors.append(str(error)))
        try:
            run(page)
            assert not errors, errors
            print('[ok] 8 browser scenarios; no page errors')
        finally:
            browser.close()
